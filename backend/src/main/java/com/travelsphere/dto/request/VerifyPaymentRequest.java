package com.travelsphere.dto.request;

import jakarta.validation.constraints.NotBlank;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class VerifyPaymentRequest {

    /**
     * The internal payment attempt reference (UUID).
     */
    @NotBlank(message = "Attempt reference is required")
    private String attemptReference;

    /**
     * The Razorpay order ID (e.g. order_EKfUsjf8912Jka).
     */
    @NotBlank(message = "Razorpay order ID is required")
    private String razorpayOrderId;

    /**
     * The Razorpay payment ID returned after customer authorization (e.g. pay_29A107xDqW175q).
     */
    @NotBlank(message = "Razorpay payment ID is required")
    private String razorpayPaymentId;

    /**
     * The HMAC-SHA256 signature generated by Razorpay.
     */
    @NotBlank(message = "Razorpay signature is required")
    private String razorpaySignature;
}
